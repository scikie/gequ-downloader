//! Gequke 歌曲爬虫工具 - 主入口
//! 
//! 本项目是一个异步Rust应用程序，使用tokio运行时。
//! 
//! 【知识点：Rust模块系统】
//! Rust使用mod关键字声明模块，默认情况下模块是私有的。
//! 使用pub关键字可以让模块对外可见。
//! 模块的查找规则：
//! - 内联模块: mod xxx { ... }
//! - 文件模块: 同目录下的 xxx.rs 文件
//! - 目录模块: xxx/mod.rs 或 xxx.rs + xxx/ 目录

mod config;
mod database;
mod models;
mod crawlers;
mod cli;

// 【知识点：anyhow错误处理库】
// anyhow是Rust中流行的错误处理库，特点：
// 1. 使用 anyhow::Result<T> 替代 std::result::Result<T, E>
// 2. 自动处理错误传播，无需显式定义错误类型
// 3. 提供 .context() 方法添加错误上下文
// 4. 适合应用程序开发（vs thiserror更适合库开发）
use anyhow::Result;

// 【知识点：tokio异步运行时】
// #[tokio::main] 宏将main函数转换为异步函数
// 它会初始化tokio运行时并执行异步main函数
// 
// tokio是Rust最流行的异步运行时，提供：
// - 任务调度器（多线程工作窃取）
// - 异步IO（网络、文件）
// - 定时器
// - 通道等同步原语
//
// 异步函数使用 async fn 定义，调用时使用 .await
// async fn 返回一个实现了Future trait的状态机
#[tokio::main]
async fn main() -> Result<()> {
    // 【知识点：? 操作符】
    // ? 是Rust的错误传播语法糖：
    // - 如果结果是 Ok(v)，解包值v
    // - 如果结果是 Err(e)，立即返回错误
    // 相当于：match cli::run().await { Ok(v) => v, Err(e) => return Err(e) }
    // 
    // 与.unwrap()/.expect()的区别：
    // - ? 会传播错误，适合生产代码
    // - unwrap() 遇到错误会panic，适合原型/测试
    cli::run().await
}

